## Kullanım Koşulları

Notti Blu bir seyahat rota paylaşım ve keşif platformudur.

Kullanıcılar:

* Doğru bilgi paylaşmayı,
* Başkalarının deneyimlerine saygı göstermeyi,
* Platformu kötüye kullanmamayı kabul eder.

Notti Blu, gerekli durumlarda içerikleri düzenleme veya kaldırma hakkını saklı tutar.
